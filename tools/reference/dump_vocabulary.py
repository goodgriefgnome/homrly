"""
Writes src/vocabulary-data.ts: the tokens of the decoder's branches in the order of the
model's outputs, from homr's own vocabulary.

  HOMR_DIR=../homr python -I tools/reference/dump_vocabulary.py
"""

import json
import os
import sys

sys.path.insert(0, os.environ["HOMR_DIR"])

from homr.transformer.vocabulary import Vocabulary  # noqa: E402


def tokens(vocab: dict[str, int]) -> list[str]:
    result = [""] * len(vocab)
    for token, index in vocab.items():
        result[index] = token
    assert all(result), "the indices are not 0..n-1"
    return result


vocab = Vocabulary()
out = os.path.join(os.path.dirname(__file__), "..", "..", "src", "vocabulary-data.ts")
with open(out, "w") as f:
    f.write("// Generated by tools/reference/dump_vocabulary.py from homr's vocabulary. Do not edit.\n\n")
    for name in ["rhythm", "pitch", "lift", "articulation", "slur", "position"]:
        f.write(f"export const {name}Tokens: readonly string[] = {json.dumps(tokens(getattr(vocab, name)))}\n\n")
